# «что такое…», «объясни…», «как работает…», «… это что»
EXPLAIN = re.compile(
    r"(?i)(?<!\w)(что так\w*|что значит|что означа\w*|что за(?!\w)|объясн\w*|поясн\w*|расскаж\w*|"
    r"как работа\w*|как устроен\w*|как считат\w*|как читат\w*|как использова\w*|как торговат\w*|"
    r"зачем нуж\w*|в ч[её]м разниц\w*|чем отлича\w*|это что|что это|что такое|"
    r"what is|what's|what are|explain|how does|meaning of)(?!\w)"
)
_WORDS = re.compile(r"[^\W_]+")
# Широкие синонимы («лонг», «стоп», «уровень»…) срабатывают только в вопросе «что такое …»,
# иначе обычная фраза про лонги считалась бы вопросом о термине.
BROAD = {"long_short", "perpetual", "spot", "stop_loss", "take_profit", "support_resistance", "bull_bear",
         "memecoin", "rug_pull", "whale", "gas", "pump_dump", "listing", "margin", "liquidity"}  # fmt: skip


def is_explain(text: str) -> bool:
    return bool(EXPLAIN.search(text))


def find(text: str, *, limit: int = 2) -> list[Term]:
    """Термины в тексте: частные раньше общих — найденный кусок закрашиваем, чтобы «сквиз лонгов» не стал ещё
    и «лонгом»."""
    rest = text
    found: list[Term] = []
    for t in TERMS:
        m = t.pattern.search(rest)
        if m is None:
            continue
        found.append(t)
        rest = rest[: m.start()] + " " * (m.end() - m.start()) + rest[m.end() :]
        if len(found) >= limit:
            break
    return found


def bare(text: str, terms: list[Term]) -> bool:
    """Сообщение — почти один термин («сквиз лонгов?», «что за MVRV»): не больше трёх слов сверх него."""
    if not terms or any(t.key in BROAD for t in terms):
        return False
    rest = text
    for t in terms:
        rest = t.pattern.sub(" ", rest)
    rest = EXPLAIN.sub(" ", rest)
    return len(_WORDS.findall(rest)) <= 3


def render(terms: list[Term]) -> str:
    parts = []
    for t in terms:
        body = esc(t.text)
        parts.append(f"📖 <b>{esc(t.title)}</b>\n{body}")
    tail = [f"«{esc(t.live)}»" for t in terms if t.live]
    text = "\n\n".join(parts)
    if tail:
        text += "\n\n<i>Посмотреть на живых данных: " + ", ".join(dict.fromkeys(tail)) + "</i>"
    return text


def popular(n: int = 16) -> list[str]:
    return [t.title.split(" (")[0] for t in TERMS[:n]]
